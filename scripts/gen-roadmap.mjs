export function buildModel({ pa, hashBaseline, ledger, kernelLedger, version, assurance }) {
  const stages = stageLine(hashBaseline, ledger);
  const sect = (k) => pa.sections.find((s) => s.key === k) ?? { rows: [] };
  const num = (rows) => rows.filter((r) => typeof r.pct === "number")
    .map((r) => ({ label: r.label, pct: r.pct, measured: ["live", "ladder"].includes(evidenceClass(r)) }));
  const words = (rows) => rows.filter((r) => typeof r.pct !== "number").map((r) => r.label);
  const thesis = num(sect("zero-trust-thesis").rows);
  const build = num(sect("build-progress").rows);
  const kernel = kernelLedger?.twins ?? [];
  return {
    stages, thesis, build, kernel, assurance,
    meta: {
      caption: `v${version.version} · ${version.packageCount} packages · ${version.testCount} tests · ship-readiness ${pa.shipReadinessPct.toFixed(1)}% · Zero-Trust thesis avg ${pa.ztAvg}% · build avg ${pa.buildAvg}%`,
      provenance: "generated from the closed assurance dependency DAG + component-health + the RD-0528/RD-0361 authority ledgers; exact producer identities are in focused provenance sidecars",
      wordRows: [...words(sect("zero-trust-thesis").rows), ...words(sect("build-progress").rows)],
      // Every registry row, state normalised — the map must not drop a workstream (owner catch: v1 did).
      registry: sect("tracking-registry").rows.map((r) => ({ item: r.item, state: String(r.state) })),
    },
  };
}

