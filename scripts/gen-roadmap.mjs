/**
 * Parse one repository root and one output mode.
 */
function parseArgs(argv) {
  let root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  let rootSeen = false;
  let mode = "print";
  let modeSeen = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--root") {
      if (rootSeen || i + 1 >= argv.length || argv[i + 1].startsWith("--")) {
        throw new Error("roadmap: --root requires exactly one path");
      }
      root = resolve(argv[++i]);
      rootSeen = true;
      continue;
    }
    if (arg === "--write" || arg === "--check" || arg === "--preview" || arg === "--self-test") {
      if (modeSeen) throw new Error("roadmap: select exactly one mode");
      mode = arg.slice(2);
      modeSeen = true;
      continue;
    }
    throw new Error(`roadmap: unknown argument ${arg}`);
  }
  return { root, mode };
}

