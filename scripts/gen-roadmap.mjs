function gitFile(commit, path) {
  const listing = git(["ls-tree", "-z", "--full-tree", commit, "--", path], null);
  if (listing.length === 0) return undefined;
  const records = listing.toString("utf8").split("\0");
  if (records.at(-1) !== "") throw new Error("Git tree listing omitted its final NUL delimiter");
  records.pop();
  if (records.length !== 1) throw new Error(`Git tree listing did not identify exactly one ${path}`);
  const match = /^(100644|100755) blob ([0-9a-f]{40}|[0-9a-f]{64})\t(.+)$/u.exec(records[0]);
  if (!match || match[3] !== path) {
    throw new Error(`Git tree listing contains a non-regular or mismatched roadmap target ${path}`);
  }
  return git(["show", `${commit}:${path}`], null);
}

// The compiler pipeline ORDER is an authored fact (the stages run in this sequence); MEMBERSHIP is derived.
// The assertion below is what keeps the authored half honest: add or remove a stage in the ledger and this
// throws rather than quietly dropping a station off the map.
const PIPELINE_ORDER = Object.freeze([
  "lexer", "parser", "type-checker", "effect-checker", "gir-emitter", "governance-verifier", "runtime",
]);

export function stageLine(hashBaseline, ledger) {
  const known = Object.keys(hashBaseline?.stages ?? {});
  if (known.length === 0) throw new Error("stage-hash baseline lists no stages — fail-closed");
  const missing = known.filter((s) => !PIPELINE_ORDER.includes(s));
  const extra = PIPELINE_ORDER.filter((s) => !known.includes(s));
  if (missing.length || extra.length) {
    throw new Error(`PIPELINE_ORDER is out of sync with the stage ledger (unplaced: ${missing.join(",") || "none"} · phantom: ${extra.join(",") || "none"}) — fix the order list, do not render a partial map`);
  }
  // A stage is AUTHORITATIVE iff it has a ledger entry; the ledger names files, so strip the extension.
  const flipped = new Set((ledger?.twins ?? []).map((t) => String(t.file ?? "").replace(/\.fungi$/, "")));
  return PIPELINE_ORDER.map((name) => ({
    name,
    authoritative: flipped.has(name),
    // Every stage in the baseline is byte-pinned; that is the R3 evidence the flip ladder stands on.
    pinned: Boolean(hashBaseline.stages[name]?.sha256),
  }));
}

// Evidence class of a percent-audit row: measured (a live reading or a countable ladder) vs asserted (typed).
export function evidenceClass(row) {
  const e = row?.evidence;
  if (!e) return "none";                                     // a WORD row carries no number to evidence
  if (e.live) return "live";                                 // read from a live artifact every run
  if (Array.isArray(e.ladder) && e.ladder.length) return "ladder"; // derived from a countable set
  return "asserted";                                         // hand-typed debt — the class we are burning down
}

