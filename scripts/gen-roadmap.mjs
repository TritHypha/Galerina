function git(args, encoding = "utf8") {
  const result = spawnSync("git", args, {
    cwd: ROOT,
    encoding,
    windowsHide: true,
    maxBuffer: MAX_GIT_BYTES,
  });
  if (result.error || result.signal || result.status !== 0) {
    const reason = result.error?.message
      ?? (result.signal ? `signal ${result.signal}` : `exit ${String(result.status)}`);
    throw new Error(`roadmap provenance Git command failed (${args[0]}): ${reason}`);
  }
  return result.stdout;
}

function nulPaths(bytes, label, unique = true) {
  if (!Buffer.isBuffer(bytes)) throw new Error(`${label} did not return exact bytes`);
  let text;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch (error) {
    throw new Error(`${label} returned non-UTF-8 paths: ${error.message}`);
  }
  const paths = text.split("\0");
  if (paths.at(-1) !== "") throw new Error(`${label} omitted its final NUL delimiter`);
  paths.pop();
  if (unique && new Set(paths).size !== paths.length) throw new Error(`${label} returned duplicate paths`);
  return paths;
}

function canonicalRepositoryPath(path) {
  return typeof path === "string"
    && path.length > 0
    && path.length <= 1024
    && !path.includes("\\")
    && !path.startsWith("/")
    && !/^[A-Za-z]:/u.test(path)
    && path.split("/").every((segment) => (
      segment.length > 0 && segment !== "." && segment !== ".."
    ));
}

let graphOutputs;
function declaredGraphOutputs() {
  if (graphOutputs !== undefined) return graphOutputs;
  let policy;
  try {
    policy = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(
      boundedInput(TOOLING_POLICY_PATH),
    ));
  } catch (error) {
    throw new Error(`roadmap tooling policy refused: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (
    policy === null
    || typeof policy !== "object"
    || Array.isArray(policy)
    || policy.generators === null
    || typeof policy.generators !== "object"
    || Array.isArray(policy.generators)
  ) {
    throw new Error("roadmap tooling policy has no ordinary generator registry");
  }
  const outputs = new Set();
  for (const key of GRAPH_GENERATOR_KEYS) {
    const descriptor = Object.getOwnPropertyDescriptor(policy.generators, key);
    const value = descriptor?.value;
    if (
      descriptor === undefined
      || descriptor.get !== undefined
      || descriptor.set !== undefined
      || value === null
      || typeof value !== "object"
      || Array.isArray(value)
      || !Array.isArray(value.outputs)
      || value.outputs.length === 0
      || value.outputs.length > 1024
    ) {
      throw new Error(`roadmap tooling policy has no closed output set for ${key}`);
    }
    for (const path of value.outputs) {
      if (!canonicalRepositoryPath(path) || outputs.has(path)) {
        throw new Error(`roadmap tooling policy has a malformed or duplicate graph output for ${key}`);
      }
      outputs.add(path);
    }
  }
  graphOutputs = Object.freeze(outputs);
  return graphOutputs;
}

