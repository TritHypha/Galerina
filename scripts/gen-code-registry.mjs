#!/usr/bin/env node
// gen-code-registry.mjs — the DERIVED code registry (standard #10 "derived catalog", #219; closes cluster ①).
//
// The registry is GENERATED from the code-index, NOT hand-curated, the way rustc derives its error index
// from `error_codes!` rather than maintaining a parallel hand list.
//
// Coverage is count-owning. Numeric-tail identities come from the shared code
// grammar; descriptive identities come from a bounded lexical classifier that
// requires an actual diagnostic sink. The generator refuses missing admitted
// identities and ambiguous source tokens, so comments, examples, type-only
// strings, and negative fixtures cannot silently expand or hide the catalog.
//
// Each code is tagged: live (emitted w/ exported const) · inline (emitted, no const — R4) · dead (defined,
// never emitted — RESERVED, standard #1 wire-or-retire) · phantom (doc-only — drift, DOC-004) · ref (mention
// only). Output: build/code-registry/REGISTRY.md (browsable catalog) + registry.json (machine, for audit-coverage).
// Run after code-index.mjs:  node scripts/code-index.mjs && node scripts/gen-code-registry.mjs
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import {
  generatedOutputMatches,
  provenance,
} from "./lib/provenance.mjs"; // BLD-003 / #216 provenance sidecar
import { measureCoverageGap } from "./audit-code-catalog-coverage.mjs"; // derives the coverage caveat below
import { exitOnHelp } from "./lib/cli-help.mjs";

exitOnHelp(import.meta.url, "usage: node scripts/gen-code-registry.mjs [--check]\n  (no arguments)  regenerate build/code-registry/ from build/code-index/code-index.json\n  --check         compare without writing\n  --help, -h  print this usage and exit 0 without reading or writing");

const ROOT = process.cwd();
for (const [index, arg] of process.argv.slice(2).entries()) {
  if (arg !== "--check" || process.argv.slice(2).indexOf(arg) !== index) {
    console.error(`gen-code-registry: REFUSED unknown or repeated argument ${JSON.stringify(arg)}; nothing was written (see --help).`);
    process.exit(2);
  }
}
const CHECK = process.argv.includes("--check");
const stableCompare = (left, right) => left < right ? -1 : left > right ? 1 : 0;
let arr;
try {
  arr = JSON.parse(readFileSync(join(ROOT, "build/code-index/code-index.json"), "utf8"));
} catch {
  console.error("gen-code-registry: build/code-index/code-index.json missing — run `node scripts/code-index.mjs` first.");
  process.exit(2);
}

const statusOf = (c) => {
  const defs = (c.defs || []).length, emits = (c.emits || []).length, tests = c.tests || 0, refs = c.refs || 0;
  if (c.docOnly) return "phantom";              // doc-only mention, never in source
  if (emits > 0) return defs > 0 ? "live" : "inline"; // inline = emitted, no exported constant (R4)
  // no emit detected:
  if (defs > 0) return (tests === 0 && refs === 0) ? "dead" : "referenced";
  // dead = defined AND truly unreferenced (no emit/test/ref) → RESERVED. referenced = defined + used/tested
  // but the emit is via a pattern the indexer can't see (e.g. a positional const arg) — NOT dead.
  return "ref";                                 // referenced only, no def
};

const entries = arr.map((c) => ({
  code: c.code, family: c.family, namespace: c.namespace, status: statusOf(c),
  names: c.names || [], severities: c.severities || [],
  defs: (c.defs || []).length, emits: (c.emits || []).length, tests: c.tests || 0, docs: c.docs || 0,
})).sort((a, b) => stableCompare(a.code, b.code));

const counts = {};
for (const e of entries) counts[e.status] = (counts[e.status] || 0) + 1;
const byFamily = {};
for (const e of entries) (byFamily[e.family] ??= []).push(e);

const registry = {
  generatedFrom: "build/code-index/code-index.json",
  total: entries.length,
  counts,
  entries,
};

// Measure the catalog's own blind spots so the coverage caveat is derived, not asserted. A vacuous
// measurement must not silently become a reassuring "0 missing" — refuse to emit the note instead.
const gap = measureCoverageGap(ROOT, entries);
if (gap.vacuous) { console.error("gen-code-registry: coverage measurement was VACUOUS — refusing to write a completeness claim."); process.exit(2); }
if (gap.realMissing > 0 || gap.unclassified > 0) {
  console.error(
    `gen-code-registry: descriptive coverage REFUSED — ${gap.realMissing} admitted identity/identities missing, ${gap.unclassified} ambiguous token(s).`,
  );
  process.exit(1);
}

const md = [
  "# Galerina — Derived Code Registry (generated by scripts/gen-code-registry.mjs)", "",
  "The authoritative catalog of EVERY diagnostic/error code, GENERATED from the code-index (standard #10).",
  "Do NOT hand-edit. Regenerate: `node scripts/code-index.mjs && node scripts/gen-code-registry.mjs`.",
  `> **Coverage gate PASS:** ${gap.descriptiveIdentities} syntax-admitted descriptive identities are catalogued,`,
  `> including ${gap.signingIdentities} on the signing path; ${gap.realMissing} are missing and ${gap.unclassified} source tokens are ambiguous.`,
  "> Numeric-tail codes and descriptive identities share this catalog. Descriptive text only acquires identity",
  "> authority at a bounded diagnostic sink; comments, type positions, tests, and explicit",
  "> `code-catalog-reference` fixtures cannot mint entries. Counts are derived by",
  "> `scripts/audit-code-catalog-coverage.mjs`; generation refuses any non-zero gap.", "",
  "## Status counts", "",
  "| status | count | meaning |", "|---|---|---|",
  `| live | ${counts.live || 0} | emitted with an exported constant |`,
  `| inline | ${counts.inline || 0} | emitted, NO exported constant (R4 — Stage F) |`,
  `| referenced | ${counts.referenced || 0} | defined + used/tested, emit via a pattern the indexer can't see (NOT dead) |`,
  `| dead | ${counts.dead || 0} | defined AND truly unreferenced — RESERVED (wire or retire, std #1) |`,
  `| phantom | ${counts.phantom || 0} | doc-only mention, not in source (drift — DOC-004) |`,
  `| ref | ${counts.ref || 0} | referenced only (no def/emit) |`, "",
  "## RESERVED — defined but not emitted (std #1: tag wire-or-retire)", "",
  entries.filter((e) => e.status === "dead").map((e) => `- \`${e.code}\``).join("\n") || "(none)", "",
  "## Catalog (by family)", "",
];
for (const fam of Object.keys(byFamily).sort(stableCompare)) {
  md.push(`### ${fam} (${byFamily[fam].length})`, "", "| code | status | name(s) | severity |", "|---|---|---|---|");
  for (const e of byFamily[fam]) md.push(`| ${e.code} | ${e.status} | ${e.names.join(" / ") || "—"} | ${e.severities.join("/") || "—"} |`);
  md.push("");
}

// ── STRUCTURAL STAMP (RD-0499): make a hand-authored count UNREPRESENTABLE ───────────────────────
// A count stated in a doc behind a `<!-- registry:counts.KEY -->N` marker is OVERWRITTEN from the
// generated source on every run, so a drifted number cannot survive a regen — stronger than the A1
// drift DETECTOR (audit-artifact-drift.mjs), which only catches drift BETWEEN regens. Additive +
// idempotent: a doc with no marker is untouched; a marker already correct is a no-op (no churn).
// `total` folds in from entries.length (it lives at registry.total, not under counts).
const stampSource = { ...counts, total: entries.length };
const generatedOutputs = new Map([
  [
    join(ROOT, "build/code-registry/registry.json"),
    JSON.stringify(registry, null, 2),
  ],
  [join(ROOT, "build/code-registry/REGISTRY.md"), md.join("\n")],
  [
    join(ROOT, "build/code-registry/provenance.json"),
    JSON.stringify(provenance("gen-code-registry", ROOT), null, 2) + "\n",
  ],
]);
for (const rel of ["AGENTS.md"]) {
  let src;
  try { src = readFileSync(join(ROOT, rel), "utf8"); } catch { continue; }
  const next = src.replace(/(<!--\s*registry:counts\.([a-z]+)\s*-->)[ \t]*[\d,]*/g,
    (m, marker, key) => (key in stampSource ? `${marker}${stampSource[key]}` : m));
  generatedOutputs.set(join(ROOT, rel), next);
}

if (CHECK) {
  for (const [path, expected] of generatedOutputs) {
    let actual;
    try {
      actual = readFileSync(path, "utf8");
    } catch {
      console.error(`gen-code-registry: missing generated output ${relative(ROOT, path).replace(/\\/g, "/")}`);
      process.exitCode = 1;
      continue;
    }
    if (!generatedOutputMatches(path, actual, expected)) {
      console.error(`gen-code-registry: generated output drift ${relative(ROOT, path).replace(/\\/g, "/")}`);
      process.exitCode = 1;
    }
  }
} else {
  mkdirSync(join(ROOT, "build/code-registry"), { recursive: true });
  for (const [path, content] of generatedOutputs) {
    const current = (() => {
      try { return readFileSync(path, "utf8"); } catch { return undefined; }
    })();
    if (current !== content) {
      writeFileSync(path, content);
      if (relative(ROOT, path).replace(/\\/g, "/") === "AGENTS.md") {
        console.log("  -> stamped registry counts into AGENTS.md (drift now unrepresentable)");
      }
    }
  }
}

console.log(`gen-code-registry: ${entries.length} codes — ${Object.entries(counts).map(([k, v]) => `${k}:${v}`).join(" · ")}`);
console.log(`  -> ${CHECK ? "checked" : "wrote"} build/code-registry/REGISTRY.md + registry.json + provenance.json + AGENTS.md`);
